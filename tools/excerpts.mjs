// Cuts real source excerpts for the page's "on the Game Boy now" panel, so the page never shows invented code.
// node tools/excerpts.mjs  ->  web/excerpts.js
import fs from 'node:fs';
const read = (f) => fs.readFileSync(new URL('../' + f, import.meta.url), 'utf8').split('\n');
function after(file, marker, n, skip = 0) {
  const lines = read(file), i = lines.findIndex(l => l.includes(marker));
  if (i < 0) throw new Error(`${marker} not found in ${file}`);
  return { file, line: i + 1 + skip, code: lines.slice(i + skip, i + skip + n).join('\n') };
}
const X = {
  1: { fn: 'draw_sky()', ...after('gen/gen_sky.c', 'void draw_sky(void)', 14) },
  2: { fn: 'draw_light()', ...after('gen/gen_sky.c', 'void draw_light(void)', 14) },
  3: { fn: 'draw_clouds()', ...after('gen/gen_sky.c', 'void draw_clouds(void)', 14) },
  4: { fn: 'draw_layer()', ...after('gen/gen_ridges.c', 'rows near the ridge line can get rim light', 10) },
  5: { fn: 'draw_surface()', ...after('gen/gen_ground.c', 'void draw_surface(void)', 14) },
  6: { fn: 'draw_water()', ...after('gen/gen_ground.c', 'void draw_water(void)', 14) },
  7: { fn: 'draw_weather()', ...after('gen/gen_ground.c', 'void draw_weather(void)', 14) },
  8: { fn: 'dith_row (SM83 assembly)', ...after('gb/conv.s', '_dith_row::', 24) },
  link: { fn: 'conv_row (SM83 assembly)', ...after('gb/conv.s', '_conv_row::', 24) },
};
fs.writeFileSync(new URL('../web/excerpts.js', import.meta.url),
  '// Generated by tools/excerpts.mjs from the ROM and generator sources. Do not edit.\nwindow.SH_EXCERPTS = ' + JSON.stringify(X, null, 1) + ';\n');
console.log('wrote web/excerpts.js', Object.keys(X).length, 'excerpts');
